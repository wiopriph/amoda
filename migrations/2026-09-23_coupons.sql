-- Личный кабинет, этап 6: купоны.
-- Купоны только для вошедших. Один купон на заказ. Скидка считается от суммы вещей (subtotal), доставка не участвует.
-- Жизненный цикл использования: reserved (при оформлении) → consumed (DELIVERED или PAID) | released (CANCELLED).
-- RLS включён без политик: доступ только через service role в server/api. Запустить в Supabase SQL Editor.

create table if not exists coupons (
  id bigint generated by default as identity primary key,
  code text not null unique check (code = upper(code) and code ~ '^[A-Z0-9]{3,32}$'),
  kind text not null check (kind in ('public', 'personal')),
  discount_type text not null check (discount_type in ('percent', 'fixed')),
  value integer not null check (value > 0),
  min_subtotal integer check (min_subtotal is null or min_subtotal >= 0),
  max_discount integer check (max_discount is null or max_discount > 0),
  starts_at timestamptz not null default now(),
  ends_at timestamptz,
  max_uses integer check (max_uses is null or max_uses > 0),
  per_user_limit integer not null default 1 check (per_user_limit > 0),
  active boolean not null default true,
  note text,
  created_at timestamptz not null default now(),
  check (discount_type <> 'percent' or value <= 100)
);

-- Персональные купоны: кому выдан и до какого числа действует именно у неё
create table if not exists coupon_grants (
  coupon_id bigint not null references coupons(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  granted_at timestamptz not null default now(),
  expires_at timestamptz,
  primary key (coupon_id, user_id)
);

create table if not exists coupon_redemptions (
  id bigint generated by default as identity primary key,
  coupon_id bigint not null references coupons(id),
  user_id uuid not null references auth.users(id) on delete cascade,
  order_id bigint not null unique references orders(id) on delete cascade,
  discount integer not null check (discount >= 0),
  status text not null default 'reserved' check (status in ('reserved', 'consumed', 'released')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists coupon_redemptions_coupon_status on coupon_redemptions (coupon_id, status);
create index if not exists coupon_redemptions_user on coupon_redemptions (user_id);

alter table orders add column if not exists coupon_id bigint references coupons(id);

alter table coupons enable row level security;
alter table coupon_grants enable row level security;
alter table coupon_redemptions enable row level security;

-- Скидка в кванзах: округление вниз, не больше subtotal, не больше max_discount
create or replace function coupon_compute(
  p_discount_type text, p_value integer, p_max_discount integer, p_subtotal integer
) returns integer
language sql immutable as $$
  select least(
    p_subtotal,
    coalesce(p_max_discount, p_subtotal),
    case when p_discount_type = 'percent' then floor(p_subtotal * p_value / 100.0)::integer else p_value end
  );
$$;

-- Проверка купона для клиентки. Возвращает одну строку: ok + reason (код причины) + скидка.
-- p_lock = true берёт блокировку строки купона (для резерва внутри транзакции).
create or replace function coupon_check(
  p_user_id uuid, p_code text, p_subtotal integer, p_lock boolean default false
) returns table (ok boolean, reason text, coupon_id bigint, discount integer)
language plpgsql security definer set search_path = public as $$
declare
  c coupons%rowtype;
  g coupon_grants%rowtype;
  v_uses integer;
  v_user_uses integer;
begin
  if p_lock then
    select * into c from coupons where code = upper(trim(p_code)) for update;
  else
    select * into c from coupons where code = upper(trim(p_code));
  end if;

  if c.id is null then
    return query select false, 'not_found', null::bigint, 0; return;
  end if;

  if not c.active or c.starts_at > now() or (c.ends_at is not null and c.ends_at < now()) then
    return query select false, 'inactive', c.id, 0; return;
  end if;

  if c.kind = 'personal' then
    select * into g from coupon_grants where coupon_id = c.id and user_id = p_user_id;

    if g.coupon_id is null then
      return query select false, 'not_granted', c.id, 0; return;
    end if;

    if g.expires_at is not null and g.expires_at < now() then
      return query select false, 'expired', c.id, 0; return;
    end if;
  end if;

  if c.min_subtotal is not null and p_subtotal < c.min_subtotal then
    return query select false, 'min_subtotal', c.id, 0; return;
  end if;

  select count(*) into v_uses from coupon_redemptions where coupon_id = c.id and status <> 'released';

  if c.max_uses is not null and v_uses >= c.max_uses then
    return query select false, 'exhausted', c.id, 0; return;
  end if;

  select count(*) into v_user_uses
  from coupon_redemptions where coupon_id = c.id and user_id = p_user_id and status <> 'released';

  if v_user_uses >= c.per_user_limit then
    return query select false, 'already_used', c.id, 0; return;
  end if;

  return query select true, null::text, c.id, coupon_compute(c.discount_type, c.value, c.max_discount, p_subtotal);
end $$;

-- Резерв купона под заказ. Вызывается сразу после создания заказа в place-order.
-- Блокирует купон, поэтому два одновременных заказа с одним одноразовым купоном невозможны.
create or replace function coupon_reserve(
  p_user_id uuid, p_code text, p_subtotal integer, p_order_id bigint
) returns table (ok boolean, reason text, coupon_id bigint, discount integer)
language plpgsql security definer set search_path = public as $$
declare
  r record;
begin
  select * into r from coupon_check(p_user_id, p_code, p_subtotal, true);

  if not r.ok then
    return query select r.ok, r.reason, r.coupon_id, r.discount; return;
  end if;

  insert into coupon_redemptions (coupon_id, user_id, order_id, discount)
  values (r.coupon_id, p_user_id, p_order_id, r.discount);

  update orders set coupon_id = r.coupon_id where id = p_order_id;

  return query select true, null::text, r.coupon_id, r.discount;
end $$;

-- Списание и возврат по статусу заказа
create or replace function coupon_sync_redemption() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'CANCELLED' then
    update coupon_redemptions set status = 'released', updated_at = now()
    where order_id = new.id and status = 'reserved';
  elsif new.status = 'DELIVERED' or new.payment_status = 'PAID' then
    update coupon_redemptions set status = 'consumed', updated_at = now()
    where order_id = new.id and status = 'reserved';
  end if;

  return new;
end $$;

drop trigger if exists orders_coupon_sync on orders;

create trigger orders_coupon_sync
  after update of status, payment_status on orders
  for each row execute function coupon_sync_redemption();

