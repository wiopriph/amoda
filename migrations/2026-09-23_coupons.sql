on conflict (code) do nothing;

create or replace function grant_welcome_coupon() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  v_coupon_id bigint;
begin
  select id into v_coupon_id from coupons where note = 'welcome' and active limit 1;

  if v_coupon_id is not null then
    insert into coupon_grants (coupon_id, user_id, expires_at)
    values (v_coupon_id, new.user_id, now() + interval '30 days')
    on conflict do nothing;
  end if;

  return new;
end $$;

drop trigger if exists profiles_grant_welcome on profiles;

create trigger profiles_grant_welcome
  after insert on profiles
  for each row execute function grant_welcome_coupon();

-- Уже зарегистрированные клиентки тоже получают welcome (30 дней с сегодня)
insert into coupon_grants (coupon_id, user_id, expires_at)
select c.id, p.user_id, now() + interval '30 days'
from profiles p, coupons c
where c.note = 'welcome'
on conflict do nothing;

